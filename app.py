import json
from datetime import datetime

# Define the baseline simulated appliances (PRD Section 10)
appliances = [
    {"appliance_id": "app_1", "name": "Medical Oxygen Concentrator", "wattage": 600, "is_on": True, "is_essential": True},
    {"appliance_id": "app_2", "name": "Refrigerator", "wattage": 400, "is_on": True, "is_essential": True},
    {"appliance_id": "app_3", "name": "Air Conditioner", "wattage": 1500, "is_on": True, "is_essential": False},
    {"appliance_id": "app_4", "name": "Electric Water Heater", "wattage": 1200, "is_on": True, "is_essential": False},
    {"appliance_id": "app_5", "name": "Gaming PC & Monitor", "wattage": 500, "is_on": False, "is_essential": False}
]

load_limit_w = 2500  # Configured maximum simulated load limit
max_step_budget = 4  # Bounded number of steps
event_log = []

def log_event(stage, message):
    """Logs observations, plans, tool calls, and verifications (PRD Section 3, FR-10)."""
    timestamp = datetime.now().strftime("%H:%M:%S")
    entry = f"[{timestamp}] **{stage}**: {message}"
    event_log.append(entry)
    print(entry)

def recalculate_load():
    """Recomputes active load as the sum of wattage for appliances that are ON (FR-03)."""
    return sum(a["wattage"] for a in appliances if a["is_on"])

def get_load_state():
    """Read-only tool returning current simulated state (PRD Section 7.2)."""
    total = recalculate_load()
    return {
        "total_load_w": total,
        "load_limit_w": load_limit_w,
        "is_overloaded": total > load_limit_w,
        "appliances": appliances
    }

def switch_off_simulated_appliance(app_id):
    """Switches OFF one eligible non-essential appliance in the simulator only (FR-07)."""
    for a in appliances:
        if a["appliance_id"] == app_id:
            a["is_on"] = False
            return f"Switched OFF '{a['name']}' ({a['wattage']}W) in simulation."
    return "Appliance ID not found."

def validate_action(proposal, step, max_steps):
    """Gates every proposed agent action against application rules before execution (FR-06)[cite: 1]."""
    if step > max_steps:
        return False, f"Step budget reached ({max_steps} max steps)[cite: 1]."

    if not isinstance(proposal, dict) or "tool" not in proposal:
        return False, "Malformed AI response: missing tool field."

    tool_name = proposal.get("tool")
    allowed_tools = ["get_load_state", "switch_off_simulated_appliance", "recalculate_load", "finish_run"]

    if tool_name not in allowed_tools:
        return False, f"Prohibited tool requested: '{tool_name}'[cite: 1]."

    if tool_name == "switch_off_simulated_appliance":
        target_id = proposal.get("appliance_id")
        target = next((a for a in appliances if a["appliance_id"] == target_id), None)

        if not target:
            return False, f"Rejected: Unknown appliance ID '{target_id}'[cite: 1]."
        if target["is_essential"]:
            return False, f"Policy Violation: Cannot switch off essential/protected load '{target['name']}'[cite: 1]."
        if not target["is_on"]:
            return False, f"Rejected: Appliance '{target['name']}' is already OFF."

    return True, "Policy validation passed."

def agent_planner(state):
    """Simulates the AI agent choosing an allowed tool based on observed state (PRD Section 7.1)[cite: 1]."""
    eligible = [a for a in state["appliances"] if a["is_on"] and not a["is_essential"]]

    if not eligible:
        return {
            "tool": "finish_run",
            "status": "blocked",
            "reason": "No eligible non-essential appliances remain ON (Only protected loads left)[cite: 1]."
        }

    # Pick the highest wattage non-essential load to shed first
    eligible.sort(key=lambda x: x["wattage"], reverse=True)
    chosen = eligible[0]

    return {
        "tool": "switch_off_simulated_appliance",
        "appliance_id": chosen["appliance_id"],
        "reason": f"Shedding non-essential load '{chosen['name']}' ({chosen['wattage']}W) to reduce overload."
    }

def run_loadshield_agent():
    print("=" * 65)
    print("🛡️ LoadShield Agentic AI Execution Workflow Starting")
    print("=" * 65)

    # 1. OBSERVE initial state
    state = get_load_state()
    log_event("OBSERVE", f"Initial Total Load: {state['total_load_w']}W | Limit: {state['load_limit_w']}W[cite: 1]")

    if not state["is_overloaded"]:
        log_event("VERIFY", "System is normal. No load-shedding action needed[cite: 1].")
        return

    # Loop within step budget (PRD Section 3, FR-09)[cite: 1]
    for step in range(1, max_step_budget + 1):
        current_state = get_load_state()
        log_event("OBSERVE", f"[Step {step}/{max_step_budget}] Overload active ({current_state['total_load_w']}W > {current_state['load_limit_w']}W).")

        # 2. PLAN next action
        proposal = agent_planner(current_state)
        log_event("PLAN", f"Agent proposed tool '{proposal.get('tool')}' on '{proposal.get('appliance_id', 'N/A')}' — Reason: {proposal.get('reason')}")

        if proposal.get("tool") == "finish_run":
            log_event("STOP", proposal.get("reason"))
            break

        # 3. VALIDATE through policy guardrails
        is_valid, validation_msg = validate_action(proposal, step, max_step_budget)
        if not is_valid:
            log_event("VALIDATE (REJECTED)", validation_msg)
            log_event("STOP", "Run halted safely. Unauthorized state change blocked[cite: 1].")
            break
        log_event("VALIDATE (ACCEPTED)", validation_msg)

        # 4. ACT (Execute tool in simulator)
        act_msg = switch_off_simulated_appliance(proposal["appliance_id"])
        log_event("ACT", act_msg)

        # 5. VERIFY new load
        new_load = recalculate_load()
        if new_load <= load_limit_w:
            log_event("VERIFY", f"Recalculated load is {new_load}W <= {load_limit_w}W. Overload RESOLVED![cite: 1]")
            break
        else:
            log_event("VERIFY", f"Recalculated load is {new_load}W > {load_limit_w}W. Overload persists; continuing loop[cite: 1].")

# Execute the agent workflow right here in Colab!
run_loadshield_agent()

